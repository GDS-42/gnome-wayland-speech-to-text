"""Short feedback sounds (start, stop, cancel, error).

The WAV files are generated by ``tools/make_sounds.py`` and shipped in
``greffier/data/sounds``. Playback goes through a single reusable ``playbin``
on the GLib main thread; it never blocks the caller for more than a state
change and never raises: a missing sound card must not break dictation.
"""

from __future__ import annotations

import logging

import gi

gi.require_version("Gst", "1.0")
from gi.repository import Gst

from greffier import paths
from greffier.audio.capture import ensure_gst

log = logging.getLogger(__name__)

SOUNDS = ("start", "stop", "cancel", "error")
DEFAULT_VOLUME = 0.6
_PLAY_FLAG_AUDIO = 0x2  # GstPlayFlags.AUDIO: no video/subtitle branches


class SoundPlayer:
    """Plays one feedback sound at a time; a new sound interrupts the previous one."""

    def __init__(self, volume: float = DEFAULT_VOLUME) -> None:
        self.volume = volume
        self._playbin: Gst.Element | None = None
        self._bus: Gst.Bus | None = None
        self._handlers: list[int] = []

    def play(self, name: str) -> None:
        """Start playing ``name`` ("start", "stop", "cancel" or "error") and return."""
        try:
            self._play(name)
        except Exception:
            log.exception("cannot play sound %r", name)

    def close(self) -> None:
        """Release the audio device and the GStreamer pipeline."""
        playbin, self._playbin = self._playbin, None
        if playbin is None:
            return
        playbin.set_state(Gst.State.NULL)
        if self._bus is not None:
            for handler_id in self._handlers:
                self._bus.disconnect(handler_id)
            self._bus.remove_signal_watch()
        self._handlers.clear()
        self._bus = None

    # -- internals ----------------------------------------------------------- #

    def _play(self, name: str) -> None:
        if name not in SOUNDS:
            log.warning("unknown sound %r", name)
            return
        path = paths.package_data(f"sounds/{name}.wav")
        if not path.is_file():
            log.warning("sound file missing: %s", path)
            return
        playbin = self._playbin or self._create()
        playbin.set_state(Gst.State.NULL)
        playbin.set_property("uri", path.as_uri())
        playbin.set_property("volume", self.volume)
        if playbin.set_state(Gst.State.PLAYING) == Gst.StateChangeReturn.FAILURE:
            log.warning("cannot play sound %r (no audio output?)", name)
            playbin.set_state(Gst.State.NULL)

    def _create(self) -> Gst.Element:
        ensure_gst()
        playbin = Gst.ElementFactory.make("playbin", "greffier-sounds")
        if playbin is None:
            raise RuntimeError("GStreamer playbin is not available")
        playbin.set_property("flags", _PLAY_FLAG_AUDIO)
        bus = playbin.get_bus()
        bus.add_signal_watch()
        self._handlers = [
            bus.connect("message::eos", self._on_eos),
            bus.connect("message::error", self._on_error),
        ]
        self._playbin, self._bus = playbin, bus
        return playbin

    def _on_eos(self, _bus: Gst.Bus, _message: Gst.Message) -> None:
        # Release the output stream as soon as the sound is over.
        if self._playbin is not None:
            self._playbin.set_state(Gst.State.NULL)

    def _on_error(self, _bus: Gst.Bus, message: Gst.Message) -> None:
        err, debug = message.parse_error()
        log.warning("sound playback failed: %s (%s)", err.message, debug)
        if self._playbin is not None:
            self._playbin.set_state(Gst.State.NULL)
